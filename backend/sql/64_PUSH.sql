-- KAMPUSLINK FILE 64: PUSH (server-side reminders, MOT-3). Safe to run twice.
-- Who gets a push: students who stopped studying (phone reminders can be killed by some phones).
--   * after 1 missed day, then 3, 6 and 13 missed days (user_reminder_state.step 1..4), then nothing until
--     they study again (_touch_activity already puts step back to 0).
--   * at most 1 push a day, only on their study days, 07:00-21:59 Algiers, at their study time + 60 min
--     (18:00 + 60 if none; never later than 21:30) so a working phone reminder always comes first.
--   * "stop" wins: unsubscribed / stopped / paused students get nothing. Bac = same rules (<= 2 a day).
-- The Cloudflare Worker kl-push calls push_batch() every 15 min with the SECRET key, sends via Firebase,
-- then push_dead_tokens() for phones that are gone. Students cannot call either function.
-- Texts: kl_notification_templates kind 'comeback' (fr/en/ar); no names on the lock screen (minors).
-- Built-in text if no template.

create table if not exists public.kl_push_log (
  id      bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  day     date not null,
  step    smallint not null,
  sent_at timestamptz not null default now(),
  tokens  int not null default 0
);
create unique index if not exists kl_push_log_user_day on public.kl_push_log (user_id, day);
alter table public.kl_push_log enable row level security;          -- no policy: server only

insert into public.app_config (key, value) values
  ('push_enabled', 'true'::jsonb),
  ('push_missed_days', '[1,3,6,13]'::jsonb)
on conflict (key) do nothing;

create or replace function public.push_batch(p_limit int default 300)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  now_dz timestamp := now() at time zone 'Africa/Algiers';
  today  date := (now() at time zone 'Africa/Algiers')::date;
  steps  jsonb := coalesce((select value from public.app_config where key = 'push_missed_days'), '[1,3,6,13]');
  out    jsonb := '[]'::jsonb;
  r      record;
  tpl    record;
  title  text; body text;
begin
  if coalesce((select value from public.app_config where key = 'push_enabled'), 'true'::jsonb) <> 'true'::jsonb then
    return out;
  end if;
  if extract(hour from now_dz) < 7 or extract(hour from now_dz) >= 22 then return out; end if;

  for r in
    select s.user_id, s.step, coalesce(p.preferred_language, 'fr') as lang,
           array_agg(t.token) as tokens
      from public.user_reminder_state s
      join public.profiles p on p.id = s.user_id
      join public.push_tokens t on t.user_id = s.user_id
     where not coalesce(s.unsubscribed, false)
       and not coalesce(s.stopped, false)
       and (s.paused_until is null or s.paused_until < now())
       and s.step < 4
       and extract(isodow from now_dz)::smallint = any(coalesce(s.study_days, '{1,2,3,4,5,6,7}'::smallint[]))
       and extract(hour from now_dz) * 60 + extract(minute from now_dz) >=
           least(split_part(coalesce(nullif(s.study_time, ''), '18:00'), ':', 1)::int * 60
                 + split_part(coalesce(nullif(s.study_time, ''), '18:00'), ':', 2)::int + 60, 21 * 60 + 30)
       and today - (s.last_active_at at time zone 'Africa/Algiers')::date - 1 >= (steps ->> s.step::int)::int
       and (s.last_sent_at is null or s.last_sent_at < now() - interval '20 hours')
       and not exists (select 1 from public.kl_push_log l where l.user_id = s.user_id and l.day = today)
     group by s.user_id, s.step, p.preferred_language
     order by s.last_active_at desc
     limit greatest(p_limit, 0)
  loop
    select t.title, t.body into tpl
      from public.kl_notification_templates t
     where t.enabled and t.kind = 'comeback' and t.lang = r.lang and t.weight > 0
       and position('{name}' in t.title || t.body) = 0
     order by random() * t.weight desc limit 1;
    if tpl.body is not null then
      title := tpl.title; body := tpl.body;
    elsif r.lang = 'ar' then
      title := 'KampusLink'; body := 'بطاقاتك في انتظارك. 10 دقائق تكفي اليوم.';
    elsif r.lang = 'en' then
      title := 'KampusLink'; body := 'Your cards are waiting. 10 minutes is enough today.';
    else
      title := 'KampusLink'; body := 'Tes cartes t''attendent. 10 minutes suffisent aujourd''hui.';
    end if;
    -- mark first (at most once), the Worker sends right after
    update public.user_reminder_state set step = r.step + 1, last_sent_at = now() where user_id = r.user_id;
    insert into public.kl_push_log (user_id, day, step, tokens) values (r.user_id, today, r.step + 1, cardinality(r.tokens))
      on conflict (user_id, day) do nothing;
    out := out || jsonb_build_object('tokens', to_jsonb(r.tokens), 'title', title, 'body', body,
                                     'kind', 'comeback', 'step', r.step + 1);
  end loop;
  return out;
end
$function$;

create or replace function public.push_dead_tokens(p_tokens text[])
returns int
language sql
security definer
set search_path to 'public'
as $function$
  with d as (delete from public.push_tokens where token = any(coalesce(p_tokens, '{}')) returning 1)
  select count(*)::int from d
$function$;

revoke all on function public.push_batch(int) from public, anon, authenticated;
revoke all on function public.push_dead_tokens(text[]) from public, anon, authenticated;
grant execute on function public.push_batch(int) to service_role;
grant execute on function public.push_dead_tokens(text[]) to service_role;

